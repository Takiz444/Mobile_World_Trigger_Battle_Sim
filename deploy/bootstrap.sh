#!/usr/bin/env bash
# One-command production setup on a fresh Ubuntu 22.04/24.04 VM (written for
# Oracle Cloud's Always Free Ampere VM; works on any x86-64/ARM64 Ubuntu box).
# Safe to re-run: it updates and redeploys without touching existing secrets.
#
#   git clone <repo> trion && cd trion && git checkout multiplayer
#   ./deploy/bootstrap.sh                   # domain = <public-ip>.sslip.io (free, no DNS setup)
#   ./deploy/bootstrap.sh play.example.com  # or your own domain (A record -> this VM)
#
# What it does:
#   1. opens ports 80/443 in the VM's own firewall (Oracle images block them),
#   2. installs Docker (if missing),
#   3. writes deploy/.env with freshly generated secrets (first run only;
#      they never leave this machine),
#   4. builds and starts the stack: Postgres + PostgREST + game server +
#      Caddy (HTTPS certificate, Web client at https://<domain>/),
#   5. installs a daily database backup (deploy/backup.sh),
#   6. waits until https://<domain>/health answers.
set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE=deploy/.env
DOMAIN_ARG="${1:-}"

say() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }

# 1. Host firewall ---------------------------------------------------------
# Oracle's Ubuntu images end the INPUT chain with a REJECT rule; HTTP(S) must
# be accepted before it. This runs before Docker is installed, so the saved
# rules don't include Docker's own chains. (The cloud-side Security List must
# also allow TCP 80 and 443 from 0.0.0.0/0; see deploy/README.md.)
if sudo iptables -S INPUT 2>/dev/null | grep -q -- '-j REJECT'; then
	added=0
	for port in 80 443; do
		if ! sudo iptables -C INPUT -p tcp -m state --state NEW --dport "$port" -j ACCEPT 2>/dev/null; then
			line=$(sudo iptables -L INPUT --line-numbers -n | awk '/REJECT/ { print $1; exit }')
			say "Opening port $port in iptables"
			sudo iptables -I INPUT "$line" -p tcp -m state --state NEW --dport "$port" -j ACCEPT
			added=1
		fi
	done
	if [ "$added" = 1 ] && command -v netfilter-persistent >/dev/null 2>&1; then
		sudo netfilter-persistent save
	fi
fi

# 2. Docker --------------------------------------------------------------
if ! command -v docker >/dev/null 2>&1; then
	say "Installing Docker"
	curl -fsSL https://get.docker.com | sudo sh
fi
DC=(sudo docker compose -f deploy/docker-compose.yml --env-file "$ENV_FILE")

# 3. Secrets / settings ----------------------------------------------------
public_ip() {
	curl -fsS --max-time 10 https://checkip.amazonaws.com || curl -fsS --max-time 10 https://api.ipify.org
}
if [ ! -f "$ENV_FILE" ]; then
	domain="$DOMAIN_ARG"
	if [ -z "$domain" ]; then
		ip="$(public_ip | tr -d '[:space:]')"
		domain="${ip//./-}.sslip.io"
	fi
	say "Writing $ENV_FILE (domain $domain, new random secrets)"
	umask 077
	cat > "$ENV_FILE" <<EOF
# Generated by deploy/bootstrap.sh on $(date -u +%Y-%m-%d). Never commit this file.
TT_DOMAIN=$domain
TT_ADMIN_KEY=$(openssl rand -hex 32)
TT_TURN_TIMEOUT_SEC=43200
TT_STORE=mongo
TT_MONGO_GATEWAY_TOKEN=$(openssl rand -hex 32)
TT_MONGO_PASSWORD=$(openssl rand -hex 24)
# Set to a hosted MongoDB (e.g. Atlas) connection string to use it instead.
TT_MONGO_URI=
# Auth0 sign-in (deploy/README.md, "Auth0"); empty = the server's own passwords.
TT_AUTH0_DOMAIN=
TT_AUTH0_CLIENT_ID=
TT_AUTH0_CLIENT_SECRET=
POSTGRES_PASSWORD=$(openssl rand -hex 24)
PGRST_AUTHENTICATOR_PASSWORD=$(openssl rand -hex 24)
TT_DB_TOKEN=
EOF
elif [ -n "$DOMAIN_ARG" ]; then
	sed -i "s/^TT_DOMAIN=.*/TT_DOMAIN=$DOMAIN_ARG/" "$ENV_FILE"
fi
DOMAIN="$(grep -E '^TT_DOMAIN=' "$ENV_FILE" | cut -d= -f2-)"
STORE="$(grep -E '^TT_STORE=' "$ENV_FILE" | cut -d= -f2-)"
if [ "$STORE" = "postgrest" ]; then
	DC+=(--profile postgres)
elif [ "$STORE" = "mongo" ]; then
	if [ -n "$(grep -E '^TT_MONGO_URI=' "$ENV_FILE" | cut -d= -f2-)" ]; then
		DC+=(--profile atlas)
	else
		DC+=(--profile mongo)
	fi
fi

# 4. Build and start -------------------------------------------------------
say "Building and starting the stack (first build takes a few minutes)"
"${DC[@]}" up -d --build --remove-orphans

# 5. Daily backups ---------------------------------------------------------
say "Installing the daily backup job (/etc/cron.d/trion-backup)"
chmod +x deploy/backup.sh
echo "17 4 * * * root $(pwd)/deploy/backup.sh >> /var/log/trion-backup.log 2>&1" \
	| sudo tee /etc/cron.d/trion-backup >/dev/null

# 6. Wait for HTTPS ----------------------------------------------------------
say "Waiting for https://$DOMAIN/health (certificate issuance can take a minute)"
for _ in $(seq 1 60); do
	if curl -fsS --max-time 5 "https://$DOMAIN/health" >/dev/null 2>&1; then
		say "Live!"
		echo "  Play in a browser:     https://$DOMAIN/"
		echo "  Native builds:         set ServerConfig.PRODUCTION_URL = \"https://$DOMAIN\""
		echo "  Secrets:               $(pwd)/$ENV_FILE (keep a copy in a password manager)"
		echo "  Logs:                  ${DC[*]} logs -f"
		exit 0
	fi
	sleep 5
done
echo "Not reachable over HTTPS yet. Check: ${DC[*]} logs caddy server" >&2
echo "Most common cause: TCP 80/443 not allowed in the cloud firewall (Security List)." >&2
exit 1
